using System.Diagnostics.CodeAnalysis;
using AssCS.Utilities;

namespace AssCS.IO;

/// <summary>
/// Write an ass document as an ass file
/// </summary>
/// <param name="consumer">Program or library requesting writes</param>
[SuppressMessage("ReSharper", "InconsistentNaming")]
public class AssWriter(ConsumerInfo consumer) : FileWriter
{
    private const string EventFormatV400 =
        "Format: Marked, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text";
    private const string EventFormatV400P =
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text";
    private const string EventFormatV400PP =
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginT, MarginB, Effect, Text";

    private const string StyleFormatV400 =
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, TertiaryColour, BackColour, "
        + "Bold, Italic, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, AlphaLevel, Encoding";
    private const string StyleFormatV400P =
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        + "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding";

    /// <inheritdoc />
    public override bool Write(Document document, TextWriter writer, bool export = false)
    {
        WriteHeader(writer);
        WriteScriptInfo(document, writer);
        if (!export)
            WriteGarbage(document, writer);
        WriteStyles(document, writer);
        WriteAttachments(document, writer);
        WriteEvents(document, writer);
        if (!export)
            WriteExtradata(document, writer);
        return true;
    }

    private void WriteHeader(TextWriter writer)
    {
        writer.WriteLine("[Script Info]");
        writer.WriteLine($"; Script generated by {consumer.Name} {consumer.Version} [AssCS]");
        writer.WriteLine($"; {consumer.Website}");
    }

    private static void WriteScriptInfo(Document document, TextWriter writer)
    {
        foreach (
            var info in document
                .ScriptInfoManager.GetAll()
                .Where(kvp => !string.IsNullOrEmpty(kvp.Value))
        )
        {
            writer.WriteLine($"{info.Key}: {info.Value}");
        }
        writer.WriteLine();
    }

    private void WriteGarbage(Document document, TextWriter writer)
    {
        if (document.GarbageManager.Count == 0)
            return;

        writer.WriteLine("[Aegisub Project Garbage]");
        foreach (var prop in document.GarbageManager.GetAll())
        {
            writer.WriteLine($"{prop.Name}: {prop.Value}");
        }
        writer.WriteLine();
    }

    private static void WriteStyles(Document document, TextWriter writer)
    {
        var header = document.Version switch
        {
            AssVersion.V400 => "[V4 Styles]",
            AssVersion.V400P => "[V4+ Styles]",
            AssVersion.V400PP => "[V4++ Styles]",
            _ => "[V4+ Styles]",
        };
        writer.WriteLine(header);
        switch (document.Version)
        {
            case AssVersion.V400:
                writer.WriteLine(StyleFormatV400);
                break;
            case AssVersion.V400P:
                writer.WriteLine(StyleFormatV400P);
                break;
            case AssVersion.V400PP:
                break;
            default:
                throw new FormatException("Unknown style version");
        }

        foreach (var style in document.StyleManager.Styles)
        {
            writer.WriteLine(style.AsAss(document.Version));
        }
        writer.WriteLine();
    }

    private static void WriteAttachments(Document _, TextWriter _1)
    {
        // TODO: Attachments Manager
        // writer.WriteLine();
    }

    private static void WriteEvents(Document document, TextWriter writer)
    {
        writer.WriteLine("[Events]");
        writer.WriteLine(
            document.Version switch
            {
                AssVersion.V400 => EventFormatV400,
                AssVersion.V400P => EventFormatV400P,
                AssVersion.V400PP => EventFormatV400PP,
                _ => throw new FormatException("Unknown event format"),
            }
        );

        foreach (var @event in document.EventManager.Events)
        {
            writer.WriteLine(@event.AsAss(document.Version));
        }

        writer.WriteLine();
    }

    /// <summary>
    /// AssCS Extradata is written with the format char <c>b</c>, and the value is always base64 encoded.
    /// </summary>
    /// <param name="document">Document to write</param>
    /// <param name="writer">TextWriter writing the file</param>
    /// <remarks>
    /// This breaks compatibility with Aegisub Extradata, which uses <c>e</c> and <c>u</c> for Inline and UU encoding.
    /// </remarks>
    private static void WriteExtradata(Document document, TextWriter writer)
    {
        if (document.ExtradataManager.Get().Count == 0)
            return;

        writer.WriteLine("[Aegisub Extradata]");

        foreach (var extra in document.ExtradataManager.Get())
        {
            writer.WriteLine(
                $"Data: {extra.Id},{StringEncoder.InlineEncode(extra.Key)},b{StringEncoder.Base64Encode(extra.Value)}"
            );
        }
    }
}
